// Generates packages/chain/src/abis.ts from the compiled Foundry artifacts so the backend ABIs can never drift from the contracts.
// Run after `forge build` in contracts/:  bun run abi
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

type AbiItem = { type: string; name?: string; inputs?: Array<{ type: string }> };

const root = resolve(import.meta.dir, '..');
// A contract's artifact sits under the .sol file that declares it (BackstopFund is in Reserves.sol), so search by name.
const outDir = resolve(root, 'contracts/out');
const artifactPath = (name: string): string => {
  for (const dir of readdirSync(outDir)) {
    const p = resolve(outDir, dir, `${name}.json`);
    if (dir.endsWith('.sol') && existsSync(p)) return p;
  }
  throw new Error(`no artifact for ${name}; run forge build in contracts/`);
};
const abiOf = (name: string): AbiItem[] => JSON.parse(readFileSync(artifactPath(name), 'utf8')).abi as AbiItem[];

const keyOf = (e: AbiItem) => `${e.type}:${e.name ?? ''}:${JSON.stringify((e.inputs ?? []).map((i) => i.type))}`;
const merge = (...abis: AbiItem[][]): AbiItem[] => {
  const seen = new Map<string, AbiItem>();
  for (const abi of abis) for (const e of abi) if (!seen.has(keyOf(e))) seen.set(keyOf(e), e);
  return [...seen.values()];
};
const only = (abi: AbiItem[], ...types: string[]) => abi.filter((e) => types.includes(e.type));

// Exchange runs ExchangeLib and MarketConfigLib by delegatecall, so their events and errors show up on the Exchange.
const exchange = merge(abiOf('Exchange'), only(abiOf('ExchangeLib'), 'event', 'error'), only(abiOf('MarketConfigLib'), 'error'));

const files: Record<string, AbiItem[]> = {
  oracleAbi: abiOf('MarkOracle'),
  exchangeAbi: exchange,
  vaultAbi: abiOf('CounterVault'),
  payoutDeskAbi: abiOf('PayoutDesk'),
  backstopAbi: abiOf('BackstopFund'),
};

let out = '// GENERATED by scripts/gen-abis.ts from contracts/out. Do not edit; run `bun run abi` after `forge build`.\n\n';
for (const [name, abi] of Object.entries(files)) out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
writeFileSync(resolve(root, 'packages/chain/src/abis.ts'), out);
console.log(`wrote packages/chain/src/abis.ts (${Object.keys(files).join(', ')})`);

// The website cannot import the backend packages, but it must be able to name a contract error: a trader whose transaction
// reverts should read "the quote expired", not a raw selector. So the same errors go into web/src/live/contract-errors.js.
const errorsOnly = merge(only(exchange, 'error'), only(files.vaultAbi!, 'error'), only(files.payoutDeskAbi!, 'error'), only(files.oracleAbi!, 'error'));
const webOut = `// GENERATED by scripts/gen-abis.ts from contracts/out. Do not edit; run \`bun run abi\` after \`forge build\`.\n// Every custom error the contracts can revert with, so wallet and node errors can be decoded into names.\nexport const contractErrors = ${JSON.stringify(errorsOnly, null, 2)};\n`;
writeFileSync(resolve(root, 'web/src/live/contract-errors.js'), webOut);
console.log(`wrote web/src/live/contract-errors.js (${errorsOnly.length} errors)`);
